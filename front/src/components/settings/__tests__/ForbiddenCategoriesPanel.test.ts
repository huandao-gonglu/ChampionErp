import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { enableAutoUnmount, flushPromises, mount } from '@vue/test-utils'
import ForbiddenCategoriesPanel from '../ForbiddenCategoriesPanel.vue'
import { fetchForbiddenCategories, importForbiddenCategories } from '@/api/forbiddenCategories'
import type { BackendForbiddenCategories } from '@/types/workflow.generated'

vi.mock('@/api/forbiddenCategories', () => ({ fetchForbiddenCategories: vi.fn(), importForbiddenCategories: vi.fn() }))
enableAutoUnmount(afterEach)
const saved: BackendForbiddenCategories = { platform: 'yandex', filename: '旧名单.xlsx', imported_at: '2026-11-01T03:00:00Z', categories: [{ category_id: '123', name: '测试禁售类目' }, { category_id: '456', name: '另一类目' }] }
const open = (editable = true) => mount(ForbiddenCategoriesPanel, { props: { editable }, global: {  } })
async function choose(wrapper: ReturnType<typeof open>, file: File) {
  const input = wrapper.get('input[type="file"]')
  Object.defineProperty(input.element, 'files', { configurable: true, value: [file] })
  await input.trigger('change'); await flushPromises()
}
beforeEach(() => {
  vi.clearAllMocks()
  vi.mocked(fetchForbiddenCategories).mockResolvedValue(structuredClone(saved))
  vi.mocked(importForbiddenCategories).mockResolvedValue({ ...saved, filename: '新名单.xlsx', categories: [{ category_id: '789', name: '新类目' }] })
})
describe('禁售类目设置', () => {
  it('普通用户只能查看管理员名单', async () => {
    const wrapper = open(false); await flushPromises()
    expect(wrapper.find('input[type="file"]').exists()).toBe(false)
    expect(wrapper.text()).toContain('由管理员统一维护')
    expect(wrapper.text()).toContain('测试禁售类目')
  })
  it('展示来源和数量，可按 ID、名称搜索', async () => {
    const wrapper = open(); await flushPromises()
    expect(wrapper.text()).toContain('当前禁售类目：2 个')
    expect(wrapper.text()).toContain('旧名单.xlsx')
    expect(wrapper.text()).toContain('已启用')
    expect(wrapper.text()).toContain('2026')
    expect(importForbiddenCategories).not.toHaveBeenCalled()
    await wrapper.get('input[type="search"]').setValue('456')
    expect(wrapper.findAll('tbody tr')).toHaveLength(1)
    expect(wrapper.get('tbody').text()).toContain('另一类目')
    await wrapper.get('input[type="search"]').setValue('测试')
    expect(wrapper.get('tbody').text()).toContain('123')
    await wrapper.get('input[type="search"]').setValue('不存在')
    expect(wrapper.text()).toContain('没有匹配的类目')
    await wrapper.findAll('button').find(button => button.text() === '清空搜索')!.trigger('click')
    expect(wrapper.findAll('tbody tr')).toHaveLength(2)
  })
  it('导入成功替换名单并提示下一次预检生效', async () => {
    const wrapper = open(); await flushPromises()
    const file = new File(['xlsx'], '新名单.xlsx')
    await choose(wrapper, file)
    expect(importForbiddenCategories).toHaveBeenCalledWith(file)
    expect(wrapper.text()).toContain('已导入 1 个禁售类目，下次预检即生效')
    expect(wrapper.text()).toContain('新名单.xlsx')
    expect(wrapper.get('tbody').text()).not.toContain('123')
  })
  it('错误文件和过大文件不上传，服务端拒绝时保留旧名单', async () => {
    const wrapper = open(); await flushPromises()
    await choose(wrapper, new File(['bad'], '禁售.csv'))
    const large = new File(['x'], '禁售.xlsx')
    Object.defineProperty(large, 'size', { value: 3 * 1024 * 1024 + 1 })
    await choose(wrapper, large)
    expect(importForbiddenCategories).not.toHaveBeenCalled()
    vi.mocked(importForbiddenCategories).mockRejectedValue(new Error('第 4 行的类目 ID 必须为正整数'))
    await choose(wrapper, new File(['bad'], '禁售.xlsx'))
    expect(wrapper.get('[role="alert"]').text()).toContain('第 4 行')
    expect(wrapper.text()).toContain('旧名单.xlsx')
    expect(wrapper.findAll('tbody tr')).toHaveLength(2)
  })
  it('读取失败可重试，空名单明确显示未配置', async () => {
    vi.mocked(fetchForbiddenCategories).mockRejectedValueOnce(new Error('读取失败'))
    const wrapper = open(); await flushPromises()
    expect(wrapper.get('fieldset').attributes('disabled')).toBeDefined()
    vi.mocked(fetchForbiddenCategories).mockResolvedValue({ ...saved, categories: [], filename: '', imported_at: '' })
    await wrapper.get('[role="alert"] button').trigger('click'); await flushPromises()
    expect(wrapper.text()).toContain('尚未导入禁售名单')
    expect(wrapper.get('fieldset').attributes('disabled')).toBeUndefined()
    expect(wrapper.text()).not.toContain('已启用')
    expect(wrapper.find('table').exists()).toBe(false)
  })
  it('555 个已导入类目可以翻页查看到最后一项，搜索和每页条数变化会回到第一页', async () => {
    vi.mocked(fetchForbiddenCategories).mockResolvedValue({ ...saved, categories: Array.from({ length: 555 }, (_, index) => ({ category_id: String(10000 + index), name: `禁售类目 ${index + 1}` })) })
    const wrapper = open(); await flushPromises()
    expect(wrapper.text()).toContain('当前禁售类目：555 个')
    expect(wrapper.findAll('tbody tr')).toHaveLength(20)
    expect(wrapper.text()).toContain('第 1–20 条，共 555 条')
    const button = (text: string) => wrapper.findAll('button').find(node => node.text() === text)!
    expect(button('上一页').attributes('disabled')).toBeDefined()
    await button('下一页').trigger('click')
    expect(wrapper.get('tbody').text()).toContain('禁售类目 21')
    await wrapper.get('select').setValue(100)
    expect(wrapper.text()).toContain('第 1 / 6 页')
    expect(wrapper.findAll('tbody tr')).toHaveLength(100)
    for (let index = 0; index < 5; index++) await button('下一页').trigger('click')
    expect(wrapper.get('tbody').text()).toContain('禁售类目 555')
    expect(wrapper.text()).toContain('第 501–555 条，共 555 条')
    expect(button('下一页').attributes('disabled')).toBeDefined()
    await wrapper.get('input[type="search"]').setValue('10000')
    expect(wrapper.findAll('tbody tr')).toHaveLength(1)
    expect(wrapper.text()).toContain('第 1 / 1 页')
    expect(wrapper.text()).toContain('匹配 1 个类目')
    expect(wrapper.get('tbody').text()).toContain('禁售类目 1')
    expect(importForbiddenCategories).not.toHaveBeenCalled()
  })
  it('进入页面直接读取持久化名单，重新进入仍可看到已导入内容', async () => {
    const first = open(); await flushPromises()
    expect(first.get('tbody').text()).toContain('测试禁售类目')
    first.unmount()
    const reopened = open(); await flushPromises()
    expect(fetchForbiddenCategories).toHaveBeenCalledTimes(2)
    expect(reopened.text()).toContain('旧名单.xlsx')
    expect(reopened.get('tbody').text()).toContain('测试禁售类目')
    expect(importForbiddenCategories).not.toHaveBeenCalled()
  })
})
